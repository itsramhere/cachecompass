"""Typed Phase 2 interfaces; implementations begin in Phase 3."""
from __future__ import annotations

from collections.abc import AsyncIterator, Sequence
from typing import Protocol

from .contracts import (
    BucketId, BucketState, CacheReadResult, CacheValue, ControllerAction,
    ControllerObservation, DataSource, DemandSnapshot, EventRecord, Key,
    MigrationAttemptRecord, MigrationTask, NodeId, RequestRecord, RouteCapture,
    RoutingEpoch,
)


class OwnershipMap(Protocol):
    """Single writer publishes epochs atomically; readers capture one route."""

    def bucket_for_key(self, key: Key) -> BucketId: ...
    def old_owner(self, bucket: BucketId) -> NodeId: ...
    def final_owner(self, bucket: BucketId) -> NodeId: ...
    def capture(self, key: Key) -> RouteCapture: ...
    def state(self, bucket: BucketId) -> BucketState: ...
    def transition(self, bucket: BucketId, expected: BucketState, target: BucketState) -> RoutingEpoch: ...


class CacheClient(Protocol):
    """Each operation has an absolute deadline supplied by its caller."""

    @property
    def node_id(self) -> NodeId: ...
    async def read(self, key: Key, *, source: DataSource, deadline_ns: int) -> CacheReadResult: ...
    async def write(self, key: Key, value: CacheValue, *, deadline_ns: int) -> None: ...


class DatabaseClient(Protocol):
    """Foreground and discretionary implementations use separate bounded pools."""

    async def read_foreground(self, key: Key, *, deadline_ns: int) -> CacheValue: ...
    async def read_for_warmup(self, key: Key, *, deadline_ns: int) -> CacheValue: ...


class KeyDemandTracker(Protocol):
    """Records completed knowledge only and exposes a closed bounded window."""

    def observe(self, key: Key, bucket: BucketId, object_bytes: int, *, at_ns: int) -> None: ...
    def snapshot(self, *, start_ns: int, end_ns: int, observed_at_ns: int) -> DemandSnapshot: ...
    def reset(self, namespace: str) -> None: ...


class MigrationScheduler(Protocol):
    """Schedules explicit source/owner/timeout/accounting tasks within budgets."""

    async def submit(self, task: MigrationTask) -> None: ...
    async def results(self) -> AsyncIterator[MigrationAttemptRecord]: ...
    async def cancel_pending(self, reason: str) -> Sequence[str]: ...


class Controller(Protocol):
    """Pure policy boundary: one causal observation produces one bounded action."""

    @property
    def policy_name(self) -> str: ...
    def decide(self, observation: ControllerObservation) -> ControllerAction: ...


class MetricsSink(Protocol):
    """Append-only sink; calls may apply backpressure but may not drop silently."""

    async def emit_event(self, record: EventRecord) -> None: ...
    async def emit_request(self, record: RequestRecord) -> None: ...
    async def emit_migration(self, record: MigrationAttemptRecord) -> None: ...
    async def flush(self, *, deadline_ns: int) -> None: ...
